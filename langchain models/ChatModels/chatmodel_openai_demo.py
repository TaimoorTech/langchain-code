from langchain_openai import ChatOpenAI
from dotenv import load_dotenv

load_dotenv()

chat_model = ChatOpenAI(model='gpt-4')

chat_model_response = chat_model.invoke("What is the capital of Pakistan?", temperature=0.7, max_completion_tokens=10)
# tempeature => Controls the randomness of the model's output. A higher temperature (e.g., 0.7) makes the output more random, while a lower temperature (e.g., 0.2) makes it more deterministic.
# max_completion_tokens => Limits the maximum number of tokens (words or word pieces) in the model's response. In this case, we are limiting the response to 10 tokens.

# chat_model_response is a dictionary with the following keys:
# - 'response': The model's response to the input prompt.
# - 'content': The content of the model's response, which is the actual text generated by the model.
print(chat_model_response.content)